import type { ReflectionFeedbackBlocks } from "../../types";
import { buildLessonTree, type LessonStep, type StepChoice } from "./buildLessonTree";

/*
 * Оффлайн-сценарии: математика 7 класс (ГОСО РК), десять ключевых тем Q1–Q2.
 *
 * Как писать шаг:
 *   ok("…")              — верный ход мысли, урок идёт дальше;
 *   no("…", "вопрос…")   — типичная ошибка; второй аргумент — наводящий вопрос
 *                          или контрпример (без готового ответа!);
 *   unsure("…")          — «не уверен(а)», ведёт в hint;
 *   any("…")             — вопрос «о себе», правильного нет.
 *   hint    — подсказка для «не уверен(а)»;
 *   explain — разбор после второй ошибки (здесь уже можно объяснить прямо);
 *   focus   — короткое имя шага для блока «Где ты застрял».
 * Порядок кнопок перемешивается автоматически, писать верный ответ можно первым.
 */

const ok = (label: string): StepChoice => ({ label, kind: "correct" });
const no = (label: string, feedback: string): StepChoice => ({
  label,
  kind: "wrong",
  feedback,
});
const unsure = (label: string): StepChoice => ({ label, kind: "unsure" });
const any = (label: string): StepChoice => ({ label, kind: "neutral" });

/** Исходник сценария: из него строится дерево, и его же учитель открывает в редакторе. */
export interface LessonSource {
  topicId: string;
  steps: LessonStep[];
  reflection: ReflectionFeedbackBlocks;
}

function lesson(
  topicId: string,
  steps: LessonStep[],
  reflection: ReflectionFeedbackBlocks
): LessonSource {
  return { topicId, steps, reflection };
}

